def main():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row

    # 作物名→IDのマップ作成
    rows = conn.execute("SELECT id, name FROM crops").fetchall()
    name_to_id = {row["name"]: row["id"] for row in rows}

    inserted = 0
    skipped_unknown = 0
    skipped_dup = 0

    print("=== コンパニオンプランツ登録開始 ===\n")

    for crop_name, companion_name, effect, is_positive in COMPANION_DATA:
        crop_id = name_to_id.get(crop_name)
        companion_id = name_to_id.get(companion_name)

        if not crop_id or not companion_id:
            print(f"[SKIP:不明] {crop_name} × {companion_name}")
            skipped_unknown += 1
            continue

        # 重複チェック
        exists = conn.execute(
            "SELECT id FROM companion_plants WHERE crop_id=? AND companion_id=?",
            [crop_id, companion_id]
        ).fetchone()

        if exists:
            skipped_dup += 1
            continue

        conn.execute(
            "INSERT INTO companion_plants (crop_id, companion_id, effect, is_positive) VALUES (?,?,?,?)",
            [crop_id, companion_id, effect, is_positive]
        )
        label = "相性良" if is_positive else "相性悪"
        print(f"[{label}] {crop_name} × {companion_name}")
        inserted += 1

    conn.commit()
    conn.close()

    print(f"\n=== 完了: {inserted}件登録, {skipped_dup}件重複スキップ, {skipped_unknown}件不明スキップ ===")

    # 集計レポート
    conn2 = sqlite3.connect(DB_PATH)
    total = conn2.execute("SELECT COUNT(*) FROM companion_plants").fetchone()[0]
    positive = conn2.execute("SELECT COUNT(*) FROM companion_plants WHERE is_positive=1").fetchone()[0]
    negative = conn2.execute("SELECT COUNT(*) FROM companion_plants WHERE is_positive=0").fetchone()[0]
    linked = conn2.execute("SELECT COUNT(DISTINCT crop_id) FROM companion_plants").fetchone()[0]
    crops_total = conn2.execute("SELECT COUNT(*) FROM crops").fetchone()[0]
    print(f"\n  合計: {total}件（相性良:{positive} / 相性悪:{negative}）")
    print(f"  コンパニオンプランツあり: {linked}/{crops_total} 品種")
    conn2.close()


if __name__ == "__main__":
    main()
