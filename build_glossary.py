def main():
    conn = sqlite3.connect(DB_PATH)

    conn.execute(DDL)

    inserted = 0
    skipped = 0

    for term, reading, plain_ja, category in TERMS:
        exists = conn.execute("SELECT id FROM glossary WHERE term=?", [term]).fetchone()
        if exists:
            skipped += 1
            continue
        conn.execute(
            "INSERT INTO glossary (term, reading, plain_ja, category) VALUES (?,?,?,?)",
            [term, reading, plain_ja, category]
        )
        inserted += 1

    conn.commit()

    total = conn.execute("SELECT COUNT(*) FROM glossary").fetchone()[0]
    conn.close()

    print(f"完了: {inserted}件登録, {skipped}件スキップ（計{total}件）")
    print("\nカテゴリ別:")
    conn2 = sqlite3.connect(DB_PATH)
    for row in conn2.execute("SELECT category, COUNT(*) FROM glossary GROUP BY category ORDER BY category"):
        print(f"  {row[0]}: {row[1]}件")
    conn2.close()


if __name__ == "__main__":
    main()
